/** Lower-case word stems without stop words: "Which positions need attention?" -> ["position", "need", "attention"]. */
export function tokenize(text: string): string[] {
  const out: string[] = [];
  for (const raw of text.toLowerCase().split(/[^a-z0-9]+/)) {
    if (raw.length < 2 || STOPWORDS.has(raw)) continue;
    const stem =
      raw.length > 3 && raw.endsWith('s') && !raw.endsWith('ss') ? raw.slice(0, -1) : raw;
    if (!out.includes(stem)) out.push(stem);
  }
  return out;
}

const keywordSets = new Map<QuestionId, Set<string>>(
  QUESTIONS.map((q) => [
    q.id,
    new Set([...tokenize(q.text), ...q.keywords.flatMap((k) => tokenize(k))]),
  ]),
);

export interface QuestionMatch {
  question: FixedQuestion;
  /** Number of typed word stems the fixed question shares. */
  score: number;
}

/** The fixed question sharing the most word stems with the typed text; ties keep the earlier question; null when none overlap. */
export function matchQuestion(text: string): QuestionMatch | null {
  const tokens = tokenize(text);
  let best: QuestionMatch | null = null;
  for (const question of QUESTIONS) {
    const set = keywordSets.get(question.id);
    const score = set === undefined ? 0 : tokens.filter((t) => set.has(t)).length;
    if (score > 0 && (best === null || score > best.score)) best = { question, score };
  }
  return best;
}

